function svg(nom, dessin) {
  const lignes = dessin.trim().split('\n');
  if (lignes.length > 16) throw new Error(`${nom} : ${lignes.length} lignes`);
  const rects = [];
  lignes.forEach((ligne, y) => {
    if (ligne.length !== 16) throw new Error(`${nom}, ligne ${y} : ${ligne.length} pixels (${ligne})`);
    for (let x = 0; x < 16; ) {
      let fin = x;
      while (fin + 1 < 16 && ligne[fin + 1] === ligne[x]) fin++; // fusionne les pixels voisins de même couleur
      if (ligne[x] !== '.') rects.push(`<rect x="${x}" y="${y}" width="${fin - x + 1}" height="1" fill="${PALETTE[ligne[x]]}"/>`);
      x = fin + 1;
    }
  });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" shape-rendering="crispEdges">${rects.join('')}</svg>\n`;
}


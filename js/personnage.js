const FIXES = { k: '#2b1d2e', w: '#fff4dc', b: '#5a2e1f', y: '#f7c548', P: '#4a3346', B: '#3a1c12', z: '#2b1d2e55', r: '#d9472b' };
export const ORDRE_OBJETS = ['bottes', 'armure', 'casque', 'bouclier', 'epee']; // ordre d'empilement

function empiler(calques) {
  const pixels = Array.from({ length: 32 }, () => Array(32).fill(null));
  for (const { lignes, couleurs } of calques)
    lignes.forEach((l, y) => [...l].forEach((c, x) => { if (c !== '.') pixels[y][x] = couleurs[c]; }));
  return pixels;
}

function versSvg(pixels, { taille, x0 = 0, y0 = 0, l = 32, h = 32, titre }) {
  const rects = [];
  for (let y = y0; y < y0 + h; y++) {
    for (let x = x0; x < x0 + l; ) {
      const c = pixels[y][x];
      let fin = x;
      while (fin + 1 < x0 + l && pixels[y][fin + 1] === c) fin++;
      if (c) rects.push(`<rect x="${x}" y="${y}" width="${fin - x + 1}" height="1" fill="${c}"/>`);
      x = fin + 1;
    }
  }
  const echelle = Math.max(1, Math.floor(taille / Math.max(l, h))); // agrandissement entier : pixels nets
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${x0} ${y0} ${l} ${h}" width="${l * echelle}" height="${h * echelle}" shape-rendering="crispEdges" role="img" aria-label="${titre}">${rects.join('')}</svg>`;
}

const couleursObjet = id => ({ ...FIXES, ...NIVEAUX[objet(id).niveau - 1] });

/** Le personnage complet, en SVG (texte sûr : uniquement des couleurs du jeu). */
export function svgPersonnage(perso, taille = 192) {
  const base = { ...FIXES, m: '#f28c8c', ...PEAUX[perso.peau], ...TUNIQUES[perso.tunique] };
  const calques = [{ lignes: CALQUES.corps, couleurs: base }];
  if (perso.coiffure !== 'chauve' && !perso.equipe.casque) calques.push({ lignes: CALQUES[perso.coiffure], couleurs: { ...FIXES, ...CHEVEUX[perso.cheveux] } });
  for (const e of ORDRE_OBJETS) if (perso.equipe[e]) calques.push({ lignes: CALQUES[e], couleurs: couleursObjet(perso.equipe[e]) });
  return versSvg(empiler(calques), { taille, titre: 'Ton personnage' });
}

/** Un objet seul (pour la boutique), recadré sur son dessin. */
export function svgObjet(id, taille = 64) {
  const o = objet(id), lignes = CALQUES[o.emplacement];
  const ys = lignes.flatMap((l, y) => (/[^.]/.test(l) ? [y] : []));
  const xs = lignes.flatMap(l => [...l].flatMap((c, x) => (c !== '.' ? [x] : [])));
  const x0 = Math.min(...xs), y0 = Math.min(...ys);
  return versSvg(empiler([{ lignes, couleurs: couleursObjet(id) }]), {
    taille, x0, y0, l: Math.max(...xs) - x0 + 1, h: Math.max(...ys) - y0 + 1, titre: o.nom,
  });
}
